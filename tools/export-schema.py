"""Export reviewable initial DDL from the same schema used by the application."""
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from sqlalchemy.dialects import mysql, postgresql
from sqlalchemy.schema import CreateIndex, CreateTable
from server.app.schema import build_schema


def main():
    metadata, _, _, _ = build_schema()
    destination = Path(__file__).resolve().parents[1] / 'server' / 'migrations'
    destination.mkdir(exist_ok=True)
    for name, dialect in [('mysql', mysql.dialect()), ('postgresql', postgresql.dialect())]:
        statements = ['-- Initial schema v2; generated by tools/export-schema.py.\n'
                      '-- Existing v1 data is migrated by application initialization; do not drop legacy tables.']
        for table in metadata.sorted_tables:
            statements.append(str(CreateTable(table).compile(dialect=dialect)).strip() + ';')
            for index in sorted(table.indexes, key=lambda item: item.name or ''):
                statements.append(str(CreateIndex(index).compile(dialect=dialect)).strip() + ';')
        (destination / f'002_relational.{name}.sql').write_text('\n\n'.join(statements) + '\n', encoding='utf-8')
    print('Exported MySQL/PostgreSQL schema v2 DDL.')


if __name__ == '__main__':
    main()
